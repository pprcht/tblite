!> @file tblite/response/type.f90
!> Provides the response kernel and the first-order quantities of a perturbation

!> Second derivatives of the energy w.r.t. the density variables (kernel) and
!> w.r.t. the density variables and the atomic positions (response)
module tblite_response_type
   use mctc_env, only : wp
   use mctc_io, only : structure_type
   use tblite_basis_type, only : basis_type
   use tblite_blas, only : gemv, symv
   use tblite_scf_info, only : scf_info, not_used
   use tblite_scf_potential, only : potential_type
   use tblite_wavefunction_type, only : wavefunction_type
   implicit none
   private

   public :: new_kernel, new_response

   !> Second derivative of the energy w.r.t. the charges and multipole moments,
   !> laid out like the potential it generates. The multipole blocks follow the
   !> anisotropic electrostatics, quadrupoles only couple to charges and onsite.
   type, public :: kernel_type
      !> Kernel of the atomic charges, nat x nat
      real(wp), allocatable :: kat(:, :)
      !> Kernel of the shell charges, nsh x nsh
      real(wp), allocatable :: ksh(:, :)
      !> Coupling of the atomic dipole moments and charges, 3 x nat x nat
      real(wp), allocatable :: kdpat(:, :, :)
      !> Kernel of the atomic dipole moments, 3 x nat x 3 x nat
      real(wp), allocatable :: kdpdp(:, :, :, :)
      !> Coupling of the atomic quadrupole moments and charges, 6 x nat x nat
      real(wp), allocatable :: kqpat(:, :, :)
      !> Onsite kernel of the atomic quadrupole moments, 6 x 6 x nat
      real(wp), allocatable :: kqpqp(:, :, :)
   contains
      !> Reset the kernel
      procedure :: reset => reset_kernel
      !> Add the potential generated by first-order moments
      procedure :: get_potential
   end type kernel_type

   !> First-order quantities of a batch of nuclear perturbations, one column
   !> per perturbed Cartesian coordinate. The moments are input, the derivative
   !> of the potential and its contraction with the moments are output.
   type, public :: response_type
      !> Perturbed coordinate 3*(iat-1)+ic of each column
      integer, allocatable :: coord(:)
      !> First-order atomic charges, nat x npert
      real(wp), allocatable :: qat(:, :)
      !> First-order shell charges, nsh x npert
      real(wp), allocatable :: qsh(:, :)
      !> First-order atomic dipole moments, 3 x nat x npert
      real(wp), allocatable :: dpat(:, :, :)
      !> First-order atomic quadrupole moments, 6 x nat x npert
      real(wp), allocatable :: qpat(:, :, :)
      !> Derivative of the atom-resolved potential w.r.t. the perturbed
      !> coordinate at fixed moments, nat x npert
      real(wp), allocatable :: vat(:, :)
      !> Derivative of the shell-resolved potential, nsh x npert
      real(wp), allocatable :: vsh(:, :)
      !> Derivative of the dipolar potential, 3 x nat x npert
      real(wp), allocatable :: vdp(:, :, :)
      !> Derivative of the quadrupolar potential, 6 x nat x npert
      real(wp), allocatable :: vqp(:, :, :)
      !> First-order moments contracted with the derivative of the potential
      !> w.r.t. all positions, 3 x nat x npert
      real(wp), allocatable :: hessian(:, :, :)
   contains
      !> Reset the output quantities
      procedure :: reset => reset_response
   end type response_type

contains

subroutine new_kernel(self, mol, bas, info)
   !***********************************
   !* Allocate a response kernel. The charge blocks are always present,
   !* the multipole blocks only if the moments enter the energy.
   !***********************************
   !> Instance of the response kernel
   type(kernel_type), intent(out) :: self
   !> Molecular structure data
   type(structure_type), intent(in) :: mol
   !> Description of the basis set
   type(basis_type), intent(in) :: bas
   !> Density dependence of the energy
   type(scf_info), intent(in) :: info

   allocate(self%kat(mol%nat, mol%nat), self%ksh(bas%nsh, bas%nsh))
   if (info%dipole /= not_used) then
      allocate(self%kdpat(3, mol%nat, mol%nat), self%kdpdp(3, mol%nat, 3, mol%nat))
   end if
   if (info%quadrupole /= not_used) then
      allocate(self%kqpat(6, mol%nat, mol%nat), self%kqpqp(6, 6, mol%nat))
   end if
   call self%reset
end subroutine new_kernel

subroutine reset_kernel(self)
   !***********************************
   !* Set all allocated blocks of the kernel to zero.
   !***********************************
   !> Instance of the response kernel
   class(kernel_type), intent(inout) :: self

   if (allocated(self%kat)) self%kat(:, :) = 0.0_wp
   if (allocated(self%ksh)) self%ksh(:, :) = 0.0_wp
   if (allocated(self%kdpat)) self%kdpat(:, :, :) = 0.0_wp
   if (allocated(self%kdpdp)) self%kdpdp(:, :, :, :) = 0.0_wp
   if (allocated(self%kqpat)) self%kqpat(:, :, :) = 0.0_wp
   if (allocated(self%kqpqp)) self%kqpqp(:, :, :) = 0.0_wp
end subroutine reset_kernel

subroutine get_potential(self, wfn, pot)
   !***********************************
   !* Add the potential generated by the first-order charges and multipole
   !* moments in wfn to pot. Only the first spin channel is used.
   !***********************************
   !> Instance of the response kernel
   class(kernel_type), intent(in) :: self
   !> First-order charges and multipole moments
   type(wavefunction_type), intent(in) :: wfn
   !> Response potential
   type(potential_type), intent(inout) :: pot

   integer :: iat

   call symv(self%kat, wfn%qat(:, 1), pot%vat(:, 1), beta=1.0_wp)
   call symv(self%ksh, wfn%qsh(:, 1), pot%vsh(:, 1), beta=1.0_wp)
   if (allocated(self%kdpat)) then
      call gemv(self%kdpat, wfn%qat(:, 1), pot%vdp(:, :, 1), beta=1.0_wp)
      call gemv(self%kdpat, wfn%dpat(:, :, 1), pot%vat(:, 1), beta=1.0_wp, trans="T")
      call gemv(self%kdpdp, wfn%dpat(:, :, 1), pot%vdp(:, :, 1), beta=1.0_wp)
   end if
   if (allocated(self%kqpat)) then
      call gemv(self%kqpat, wfn%qat(:, 1), pot%vqp(:, :, 1), beta=1.0_wp)
      call gemv(self%kqpat, wfn%qpat(:, :, 1), pot%vat(:, 1), beta=1.0_wp, trans="T")
      do iat = 1, size(self%kqpqp, 3)
         pot%vqp(:, iat, 1) = pot%vqp(:, iat, 1) &
            & + matmul(self%kqpqp(:, :, iat), wfn%qpat(:, iat, 1))
      end do
   end if
end subroutine get_potential

subroutine new_response(self, mol, bas, coord)
   !***********************************
   !* Allocate the first-order quantities for the perturbation of the given
   !* Cartesian coordinates and set them to zero.
   !***********************************
   !> Instance of the first-order quantities
   type(response_type), intent(out) :: self
   !> Molecular structure data
   type(structure_type), intent(in) :: mol
   !> Description of the basis set
   type(basis_type), intent(in) :: bas
   !> Perturbed coordinates 3*(iat-1)+ic
   integer, intent(in) :: coord(:)

   integer :: npert

   npert = size(coord)
   self%coord = coord
   allocate(self%qat(mol%nat, npert), self%qsh(bas%nsh, npert), &
      & self%dpat(3, mol%nat, npert), self%qpat(6, mol%nat, npert), source=0.0_wp)
   allocate(self%vat(mol%nat, npert), self%vsh(bas%nsh, npert), &
      & self%vdp(3, mol%nat, npert), self%vqp(6, mol%nat, npert), &
      & self%hessian(3, mol%nat, npert))
   call self%reset
end subroutine new_response

subroutine reset_response(self)
   !***********************************
   !* Set the derivative of the potential and its contraction to zero, the
   !* first-order moments are kept.
   !***********************************
   !> Instance of the first-order quantities
   class(response_type), intent(inout) :: self

   self%vat(:, :) = 0.0_wp
   self%vsh(:, :) = 0.0_wp
   self%vdp(:, :, :) = 0.0_wp
   self%vqp(:, :, :) = 0.0_wp
   self%hessian(:, :, :) = 0.0_wp
end subroutine reset_response

end module tblite_response_type
