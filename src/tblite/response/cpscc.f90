!> @file tblite/response/cpscc.f90
!> Provides the solver for the coupled-perturbed self-consistent charge equations

!> Coupled-perturbed equations of a self-consistent xTB wavefunction.
!> The response operator only depends on the converged wavefunction and is
!> shared by all perturbations, which enter through the right-hand side.
module tblite_response_cpscc
   use mctc_env, only : wp, error_type, fatal_error
   use mctc_io, only : structure_type
   use tblite_container, only : container_cache
   use tblite_integral_type, only : integral_type
   use tblite_response_bicgstab, only : bicgstab_solve
   use tblite_response_density, only : density_response
   use tblite_response_kernel, only : get_kernel_potential
   use tblite_scf, only : potential_type, new_potential
   use tblite_scf_iterator, only : get_qat_from_qsh
   use tblite_scf_potential, only : add_pot_to_h1
   use tblite_wavefunction_mulliken, only : get_mulliken_shell_charges, &
      & get_mulliken_atomic_multipoles
   use tblite_wavefunction_type, only : wavefunction_type, new_wavefunction
   use tblite_xtb_calculator, only : xtb_calculator
   implicit none
   private

   public :: solve_cpscc, get_response_moments, get_fock_response

   !> Convergence threshold for the relative residual of the response equations
   real(wp), parameter :: rtol = 1.0e-9_wp

contains

subroutine solve_cpscc(mol, calc, wfn, ints, ccache, dcache, rhs, dp, error, kat)
   !***********************************
   !* Solve the coupled-perturbed equations (1 - A) dp = rhs, where A maps a
   !* first-order density matrix to the uncoupled response to the potential
   !* generated by its charges and multipole moments.
   !***********************************
   !> Molecular structure data
   type(structure_type), intent(in) :: mol
   !> Single-point calculator
   type(xtb_calculator), intent(in) :: calc
   !> Converged wavefunction data
   type(wavefunction_type), intent(in) :: wfn
   !> Integrals at the current geometry
   type(integral_type), intent(in) :: ints
   !> Cache of the electrostatic container
   type(container_cache), intent(inout) :: ccache
   !> Cache of the dispersion container
   type(container_cache), intent(inout) :: dcache
   !> Uncoupled response to the perturbation
   real(wp), contiguous, intent(in) :: rhs(:, :, :)
   !> First-order density matrix
   real(wp), contiguous, intent(out) :: dp(:, :, :)
   !> Error handling
   type(error_type), allocatable, intent(out) :: error
   !> Atom-resolved charge kernel of additional interactions
   real(wp), intent(in), optional :: kat(:, :)

   real(wp) :: resnorm
   real(wp), allocatable :: fock(:, :, :)
   type(potential_type) :: pot
   type(wavefunction_type) :: wfn_k
   type(error_type), allocatable :: kernel_error

   call new_potential(pot, mol, calc%bas, wfn%nspin)
   call new_wavefunction(wfn_k, mol%nat, calc%bas%nsh, calc%bas%nao, wfn%nspin, wfn%kt)
   allocate(fock(calc%bas%nao, calc%bas%nao, 1))

   call bicgstab_solve(rhs, apply_operator, rtol, dp, resnorm)
   if (allocated(kernel_error)) then
      call move_alloc(kernel_error, error)
      return
   end if
   !>-- written to fail for a NaN residual as well
   if (.not.(resnorm < rtol)) then
      call fatal_error(error, "Coupled-perturbed equations did not converge")
   end if

contains

   subroutine apply_operator(x, y)
      !***********************************
      !* Action of the response operator, y = x - A x.
      !***********************************
      !> Trial vector
      real(wp), intent(in) :: x(:, :, :)
      !> Image of the trial vector
      real(wp), intent(out) :: y(:, :, :)

      type(error_type), allocatable :: local_error

      call get_response_moments(calc, ints, x, wfn_k)
      call pot%reset
      call get_kernel_potential(mol, calc, ccache, dcache, wfn, wfn_k, pot, local_error, kat)
      if (allocated(local_error) .and. .not.allocated(kernel_error)) then
         call move_alloc(local_error, kernel_error)
      end if
      call get_fock_response(calc, ints, pot, fock)
      call density_response(wfn, fock(:, :, 1), y(:, :, 1))
      y(:, :, :) = x - y
   end subroutine apply_operator

end subroutine solve_cpscc

subroutine get_response_moments(calc, ints, pmat, wfn_r)
   !***********************************
   !* Mulliken charges and atomic multipole moments of a first-order density
   !* matrix. The multipole moments are only evaluated if they enter the
   !* Hamiltonian and are set to zero otherwise.
   !***********************************
   !> Single-point calculator
   type(xtb_calculator), intent(in) :: calc
   !> Integrals at the current geometry
   type(integral_type), intent(in) :: ints
   !> First-order density matrix
   real(wp), intent(in) :: pmat(:, :, :)
   !> Wavefunction to store the moments
   type(wavefunction_type), intent(inout) :: wfn_r

   real(wp), allocatable :: n0sh(:)

   allocate(n0sh(calc%bas%nsh), source=0.0_wp)
   call get_mulliken_shell_charges(calc%bas, ints%overlap, pmat, n0sh, wfn_r%qsh)
   call get_qat_from_qsh(calc%bas, wfn_r%qsh, wfn_r%qat)
   if (allocated(calc%coulomb%aes2)) then
      call get_mulliken_atomic_multipoles(calc%bas, ints%dipole, pmat, wfn_r%dpat)
      call get_mulliken_atomic_multipoles(calc%bas, ints%quadrupole, pmat, wfn_r%qpat)
   else
      wfn_r%dpat(:, :, :) = 0.0_wp
      wfn_r%qpat(:, :, :) = 0.0_wp
   end if
end subroutine get_response_moments

subroutine get_fock_response(calc, ints, pot, fock)
   !***********************************
   !* Perturbation of the Hamiltonian generated by a potential. The atom and
   !* shell resolved parts of the potential are expanded to the orbitals.
   !***********************************
   !> Single-point calculator
   type(xtb_calculator), intent(in) :: calc
   !> Integrals at the current geometry
   type(integral_type), intent(in) :: ints
   !> Potential
   type(potential_type), intent(inout) :: pot
   !> Perturbation of the Hamiltonian
   real(wp), intent(out) :: fock(:, :, :)

   call add_pot_to_h1(calc%bas, ints, pot, fock)
   fock(:, :, 1) = fock(:, :, 1) - ints%hamiltonian
end subroutine get_fock_response

end module tblite_response_cpscc
