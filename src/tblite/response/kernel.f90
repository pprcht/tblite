!> @file tblite/response/kernel.f90
!> Provides the charge and multipole response kernel of the xTB Hamiltonian

!> Linear response of the self-consistent potential to a change in the
!> atomic charges and multipole moments
module tblite_response_kernel
   use dftd4_model_d4, only : d4_model
   use mctc_env, only : wp, error_type, fatal_error
   use mctc_io, only : structure_type
   use tblite_container, only : container_cache
   use tblite_disp_cache, only : dispersion_cache
   use tblite_disp_d4, only : d4_dispersion
   use tblite_scf_potential, only : potential_type
   use tblite_wavefunction_type, only : wavefunction_type
   use tblite_xtb_calculator, only : xtb_calculator
   implicit none
   private

   public :: get_kernel_potential, has_dispersion_kernel

contains

subroutine get_kernel_potential(mol, calc, ccache, dcache, wfn, wfn_r, pot, error)
   !***********************************
   !* Add the potential generated by the first-order charges and multipole
   !* moments in wfn_r to pot. The kernel is the second derivative of the
   !* self-consistent energy at the converged state in wfn, hence linear
   !* in the response moments.
   !***********************************
   !> Molecular structure data
   type(structure_type), intent(in) :: mol
   !> Single-point calculator
   type(xtb_calculator), intent(in) :: calc
   !> Cache of the electrostatic container
   type(container_cache), intent(inout) :: ccache
   !> Cache of the dispersion container
   type(container_cache), intent(inout) :: dcache
   !> Converged wavefunction data
   type(wavefunction_type), intent(in) :: wfn
   !> First-order charges and multipole moments
   type(wavefunction_type), intent(in) :: wfn_r
   !> Response potential
   type(potential_type), intent(inout) :: pot
   !> Error handling
   type(error_type), allocatable, intent(out) :: error

   call calc%coulomb%get_potential(mol, ccache, wfn_r, pot)
   call linearize_thirdorder(mol, calc, wfn, wfn_r, pot)
   if (has_dispersion_kernel(calc)) then
      call add_dispersion_kernel(mol, calc, dcache, wfn, wfn_r, pot, error)
   end if
end subroutine get_kernel_potential

pure function has_dispersion_kernel(calc) result(has_kernel)
   !***********************************
   !* Whether the dispersion correction depends on the atomic charges and
   !* therefore contributes to the response kernel.
   !***********************************
   !> Single-point calculator
   type(xtb_calculator), intent(in) :: calc
   !> Dispersion enters the response kernel
   logical :: has_kernel

   has_kernel = .false.
   if (.not.allocated(calc%dispersion)) return
   select type(disp => calc%dispersion)
   type is (d4_dispersion)
      has_kernel = .true.
   class default
      has_kernel = .false.
   end select
end function has_dispersion_kernel

subroutine linearize_thirdorder(mol, calc, wfn, wfn_r, pot)
   !***********************************
   !* The onsite third-order potential is quadratic in the charges, so the
   !* container evaluated at the response charges yields hub*dq**2.
   !* Replace it by the linearization 2*hub*q*dq at the converged charges.
   !***********************************
   !> Molecular structure data
   type(structure_type), intent(in) :: mol
   !> Single-point calculator
   type(xtb_calculator), intent(in) :: calc
   !> Converged wavefunction data
   type(wavefunction_type), intent(in) :: wfn
   !> First-order charges and multipole moments
   type(wavefunction_type), intent(in) :: wfn_r
   !> Response potential
   type(potential_type), intent(inout) :: pot

   integer :: iat, izp, ii, ish
   real(wp) :: hub

   if (.not.allocated(calc%coulomb%es3)) return

   associate(es3 => calc%coulomb%es3)
      if (es3%shell_resolved) then
         do iat = 1, mol%nat
            izp = mol%id(iat)
            ii = es3%ish_at(iat)
            do ish = 1, es3%nsh_at(iat)
               hub = es3%hubbard_derivs(ish, izp)
               pot%vsh(ii+ish, 1) = pot%vsh(ii+ish, 1) - hub*wfn_r%qsh(ii+ish, 1)**2 &
                  & + 2*hub*wfn%qsh(ii+ish, 1)*wfn_r%qsh(ii+ish, 1)
            end do
         end do
      else
         do iat = 1, mol%nat
            izp = mol%id(iat)
            hub = es3%hubbard_derivs(1, izp)
            pot%vat(iat, 1) = pot%vat(iat, 1) - hub*wfn_r%qat(iat, 1)**2 &
               & + 2*hub*wfn%qat(iat, 1)*wfn_r%qat(iat, 1)
         end do
      end if
   end associate
end subroutine linearize_thirdorder

subroutine add_dispersion_kernel(mol, calc, dcache, wfn, wfn_r, pot, error)
   !***********************************
   !* Add the second charge derivative of the self-consistent D4 dispersion
   !* energy contracted with the response charges to the atomic potential.
   !* The reference weights are gw = gwk*zeta(q), with the logarithmic charge
   !* derivative g = dgw/dq / gw and dg/dq = g*(c*qref/u**2 - 2/u), where
   !* u = q + zeff and c = eta*gc.
   !***********************************
   !> Molecular structure data
   type(structure_type), intent(in) :: mol
   !> Single-point calculator
   type(xtb_calculator), intent(in) :: calc
   !> Cache of the dispersion container
   type(container_cache), intent(inout) :: dcache
   !> Converged wavefunction data
   type(wavefunction_type), intent(in) :: wfn
   !> First-order charges and multipole moments
   type(wavefunction_type), intent(in) :: wfn_r
   !> Response potential
   type(potential_type), intent(inout) :: pot
   !> Error handling
   type(error_type), allocatable, intent(out) :: error

   integer :: mref, iat, jat, izp, jzp, iref, jref
   real(wp) :: c, u, qref, g, dg, gw, ha, hb, w6
   real(wp), allocatable :: gwvec(:, :, :), gwdcn(:, :, :), gwdq(:, :, :), gwd2q(:, :)
   type(dispersion_cache), pointer :: ptr
   real(wp), parameter :: small = 1.0e-12_wp

   call view(dcache, ptr)
   if (.not.associated(ptr)) then
      call fatal_error(error, "Dispersion cache is not initialized")
      return
   end if

   select type(disp => calc%dispersion)
   type is (d4_dispersion)
      select type(model => disp%model)
      type is (d4_model)
         mref = maxval(model%ref)
         allocate(gwvec(mref, mol%nat, model%ncoup), gwdcn(mref, mol%nat, model%ncoup), &
            & gwdq(mref, mol%nat, model%ncoup), gwd2q(mref, mol%nat), source=0.0_wp)

         call model%weight_references(mol, ptr%cn, wfn%qat(:, 1), gwvec, gwdcn, gwdq)

         do iat = 1, mol%nat
            izp = mol%id(iat)
            c = model%eta(izp) * model%gc
            u = wfn%qat(iat, 1) + model%zeff(izp)
            if (abs(u) < small) cycle
            do iref = 1, model%ref(izp)
               gw = gwvec(iref, iat, 1)
               if (abs(gw) < tiny(1.0_wp)) cycle
               qref = model%q(iref, izp) + model%zeff(izp)
               g = gwdq(iref, iat, 1) / gw
               dg = g * (c*qref/u**2 - 2.0_wp/u)
               gwd2q(iref, iat) = gw * (g*g + dg)
            end do
         end do

         !>-- the cached matrix holds the damped reference C6 of all pairs
         do iat = 1, mol%nat
            izp = mol%id(iat)
            do jat = 1, mol%nat
               jzp = mol%id(jat)
               ha = 0.0_wp
               hb = 0.0_wp
               do iref = 1, model%ref(izp)
                  do jref = 1, model%ref(jzp)
                     w6 = ptr%dispmat(iref, iat, jref, jat)
                     ha = ha + gwd2q(iref, iat) * gwvec(jref, jat, 1) * w6
                     hb = hb + gwdq(iref, iat, 1) * gwdq(jref, jat, 1) * w6
                  end do
               end do
               pot%vat(iat, 1) = pot%vat(iat, 1) &
                  & + ha*wfn_r%qat(iat, 1) + hb*wfn_r%qat(jat, 1)
            end do
         end do
      class default
         call fatal_error(error, "Response kernel is only available for the D4 model")
      end select
   class default
      call fatal_error(error, "Response kernel requires self-consistent D4 dispersion")
   end select
end subroutine add_dispersion_kernel

subroutine view(cache, ptr)
   !***********************************
   !* Return a pointer to the dispersion cache stored in a container cache.
   !***********************************
   !> Reusable data container
   type(container_cache), target, intent(inout) :: cache
   !> Dispersion cache, unassociated if the container holds something else
   type(dispersion_cache), pointer, intent(out) :: ptr

   nullify(ptr)
   if (.not.allocated(cache%raw)) return
   select type(target => cache%raw)
   type is (dispersion_cache)
      ptr => target
   class default
      nullify(ptr)
   end select
end subroutine view

end module tblite_response_kernel
